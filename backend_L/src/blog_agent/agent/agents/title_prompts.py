from typing import Annotated, List

from pydantic import BaseModel, Field, StringConstraints, field_validator

# ============================================================
# 结构化输出：标题列表（title_graph 的生成节点用）
# ============================================================


class TitleList(BaseModel):
    """标题生成的结构化输出：3 个候选标题"""

    titles: List[Annotated[str, StringConstraints(strip_whitespace=True, min_length=1, max_length=30)]] = Field(
        min_length=3, max_length=3, description="3 个互不相同的候选标题，每个不超过30字"
    )

    @field_validator("titles")
    @classmethod
    def distinct_titles(cls, titles: List[str]) -> List[str]:
        if len(set(titles)) != len(titles):
            raise ValueError("候选标题重复")
        return titles


class TitleScore(BaseModel):
    """单个标题的评分结果（0-10 分制，供前端标题评分栏展示）"""

    title: str = Field(description="被评分的标题原文，必须与候选标题完全一致")
    accuracy: int = Field(description="准确性评分（0-10 整数）：标题是否准确反映文章内容，不夸大、不误导")
    uniqueness: int = Field(description="独特性评分（0-10 整数）：标题是否有新意，避免与同类文章雷同")
    seo: int = Field(description="SEO友好度评分（0-10 整数）：标题是否包含关键词，是否适合搜索引擎收录")
    total: float = Field(description="综合分（0-10，保留1位小数）= (准确性 + 独特性 + SEO友好度) / 3")
    pros: List[str] = Field(description="优点列表，2条，要具体，不要空话")
    cons: List[str] = Field(description="缺点列表，2条，要具体，不要空话")


class TitleScoreList(BaseModel):
    """标题评分结构化输出：与候选标题一一对应的评分数组"""

    scores: List[TitleScore] = Field(description="每个候选标题的评分，顺序与候选标题一致")

